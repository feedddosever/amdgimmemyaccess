// Words for a child in the 8 languages, lowercase. Used to put kid-friendly
// dishes first and to label the kitchen ticket.
const CHILD_CUES = [
  "child", "kid", "my son", "daughter", "bambin", "figli", "mein kind", "unser kind", "kinder", "sohn",
  "tochter", "enfant", "fils", "fille", "niño", "niña", "hijo", "hija", "子ども", "子供", "こども", "息子",
  "娘", "孩子", "儿子", "女儿", "ребен", "ребён", "сын", "доч",
];

export function mentionsChild(text: string | undefined): boolean {
  if (!text) return false;
  const lower = text.toLowerCase();
  return CHILD_CUES.some((cue) => lower.includes(cue));
}

export function childAge(text: string): string | undefined {
  const lower = text.toLowerCase();
  return (lower.match(/(\d{1,2})\s*(?:-?\s*year|歳|anni|jahre|ans|años|岁|лет|год)/) ?? lower.match(/\((\d{1,2})\)/))?.[1];
}
